import { util } from './index.ts';
import type { BuildMode, Config, Generator, JobCommand, Language, Project, Scope, Target, TargetType } from '../types.ts';
import { commandTargets, type JobPlan, type PlannedJob } from './jobs.ts';
import { path } from '../deps.ts';

export const CMakeMinimumRequiredMajor = 3;
export const CMakeMinimumRequiredMinor = 21;
export const CMakeMinimumRequired = `${CMakeMinimumRequiredMajor}.${CMakeMinimumRequiredMinor}`;

export function genCMakePresetsJson(config: Config, buildDir: string): string {
    const cacheVariables: Record<string, string> = {};
    if (!isMultiConfigGenerator(config)) {
        cacheVariables.CMAKE_BUILD_TYPE = asCmakeBuildMode(config.buildMode);
    }
    config.cmakeCacheVariables.forEach((v) => {
        cacheVariables[v.name] = resolveCMakeVariableValue(v.value);
    });
    const preset = {
        version: 3,
        cmakeMinimumRequired: {
            major: CMakeMinimumRequiredMajor,
            minor: CMakeMinimumRequiredMinor,
            patch: 0,
        },
        configurePresets: [
            {
                name: config.name,
                displayName: config.name,
                binaryDir: buildDir,
                generator: asCmakeGenerator(config.generator),
                architecture: config.generatorArchitecture,
                toolset: config.generatorToolset,
                toolchainFile: config.toolchainFile,
                environment: config.environment,
                // NOTE: CMAKE_BUILD_TYPE *must* exist in preset for CMakeTools to work
                cacheVariables,
            },
        ],
        buildPresets: genBuildPresets(config),
    };
    return JSON.stringify(preset, null, 2);
}

function asCmakeGenerator(g: Generator | undefined): string | undefined {
    switch (g) {
        case 'make':
            return 'Unix Makefiles';
        case 'ninja':
            return 'Ninja';
        case 'ninja-multi-config':
            return 'Ninja Multi-Config';
        case 'xcode':
            return 'Xcode';
        default:
            return undefined;
    }
}

function asCmakeScope(scope: Scope): string {
    return ` ${scope.toUpperCase()}`;
}

function asCmakeBuildMode(buildMode: BuildMode): string {
    if (buildMode === 'debug') {
        return 'Debug';
    } else {
        return 'Release';
    }
}

function isMultiConfigGenerator(config: Config): boolean {
    switch (config.generator) {
        case 'make':
        case 'ninja':
            return false;
        case 'vstudio':
        case 'ninja-multi-config':
        case 'xcode':
            return true;
        default:
            return config.platform === 'windows';
    }
}

function getTargetType(t: Target): TargetType {
    return t.overrideType ?? t.type;
}

function genBuildPresets(config: Config): unknown[] {
    if (isMultiConfigGenerator(config)) {
        return [
            { name: 'default', configurePreset: config.name, configuration: asCmakeBuildMode(config.buildMode) },
            { name: 'debug', configurePreset: config.name, configuration: asCmakeBuildMode('debug') },
            { name: 'release', configurePreset: config.name, configuration: asCmakeBuildMode('release') },
        ];
    } else {
        return [{ name: 'default', configurePreset: config.name }];
    }
}

export function genCMakeListsTxt(project: Project, config: Config, jobPlan: JobPlan): string {
    let str = '';
    str += genProlog(project, jobPlan);
    str += genCMakeVariables(project, config);
    str += genIncludeDirectories(project);
    str += genLinkDirectories(project);
    str += genCompileDefinitions(project);
    str += genCompileOptions(project);
    str += genLinkOptions(project);
    str += genJobs(project, jobPlan);
    project.cmakeCodeInjectors().forEach((injector) => {
        if (injector.location === 'before-targets') {
            str += injector.fn(project, config);
        }
    });
    for (const target of project.targets()) {
        str += genTarget(config, target);
        str += genTargetDependencies(target, jobPlan);
        str += genTargetIncludeDirectories(target);
        str += genTargetLinkDirectories(target);
        str += genTargetCompileDefinitions(target);
        str += genTargetCompileOptions(target);
        str += genTargetLinkOptions(target);
        str += genTargetProperties(target);
    }
    project.cmakeCodeInjectors().forEach((injector) => {
        if (injector.location !== 'before-targets') {
            str += injector.fn(project, config);
        }
    });
    return str;
}

function genProlog(project: Project, jobPlan: JobPlan): string {
    let str = `# machine generated by fibs, don't edit or commit to version control!\n`;
    str += `cmake_minimum_required(VERSION ${CMakeMinimumRequired})\n`;
    str += `project(${project.name()} C CXX)\n`;
    // deno is only needed at build time to run script jobs
    if (jobPlan.jobs.some((planned) => planned.jobFile !== undefined)) {
        str += `find_program(DENO deno REQUIRED)\n`;
    }
    str += 'set_property(GLOBAL PROPERTY USE_FOLDERS ON)\n';
    for (const includeDir of project.cmakeIncludes()) {
        str += `include("${includeDir.path}")\n`;
    }
    return str;
}

function resolveCMakeVariableValue(val: string | boolean): string {
    if (typeof val === 'string') {
        return val;
    } else {
        return val ? 'ON' : 'OFF';
    }
}

function genCMakeVariables(project: Project, config: Config): string {
    let str = '';
    str += 'set(CMAKE_CONFIGURATION_TYPES Debug Release)\n';
    const vars = util.deduplicate([...config.cmakeVariables, ...project.cmakeVariables()]);
    for (const cmakeVariable of vars) {
        str += `set(${cmakeVariable.name} ${resolveCMakeVariableValue(cmakeVariable.value)})\n`;
    }
    return str;
}

function compileExpr(l: Language | undefined, m: BuildMode | undefined, str: string): string {
    switch (l) {
        case 'c':
            str = `$<$<COMPILE_LANGUAGE:C>:${str}>`;
            break;
        case 'cxx':
            str = `$<$<COMPILE_LANGUAGE:CXX>:${str}>`;
            break;
    }
    switch (m) {
        case 'debug':
            str = `$<$<CONFIG:DEBUG>:${str}>`;
            break;
        case 'release':
            str = `$<$<CONFIG:RELEASE>:${str}>`;
            break;
    }
    return `"${str}"`;
}

function linkExpr(l: Language | undefined, m: BuildMode | undefined, str: string): string {
    switch (l) {
        case 'c':
            str = `$<$<LINK_LANGUAGE:C>:${str}>`;
            break;
        case 'cxx':
            str = `$<$<LINK_LANGUAGE:CXX>:${str}>`;
            break;
    }
    switch (m) {
        case 'debug':
            str = `$<$<CONFIG:DEBUG>:${str}>`;
            break;
        case 'release':
            str = `$<$<CONFIG:RELEASE>:${str}>`;
            break;
    }
    return `"${str}"`;
}

function genIncludeDirectories(project: Project): string {
    let str = '';
    project.includeDirectories().forEach((item) =>
        str += `include_directories(${item.system ? 'SYSTEM ' : ''}${compileExpr(item.language, item.buildMode, item.dir)})\n`
    );
    return str;
}

function genLinkDirectories(project: Project): string {
    let str = '';
    project.linkDirectories().forEach((item) => str += `link_directories(${compileExpr(item.language, item.buildMode, item.dir)})\n`);
    return str;
}

function genCompileDefinitions(project: Project): string {
    let str = '';
    const items = project.compileDefinitions();
    if (items.length > 0) {
        str += 'add_compile_definitions(';
        str += items.map((item) => `${compileExpr(item.language, item.buildMode, `${item.name}=${item.val}`)}`).join(' ');
        str += ')\n';
    }
    return str;
}

function genCompileOptions(project: Project): string {
    let str = '';
    const items = project.compileOptions();
    if (items.length > 0) {
        str += 'add_compile_options(';
        str += items.map((item) => `${compileExpr(item.language, item.buildMode, item.opt)}`).join(' ');
        str += ')\n';
    }
    return str;
}

function genLinkOptions(project: Project): string {
    let str = '';
    const items = project.linkOptions();
    if (items.length > 0) {
        str += 'add_link_options(';
        str += items.map((item) => `${linkExpr(item.language, item.buildMode, item.opt)}`).join(' ');
        str += ')\n';
    }
    return str;
}

function genTarget(config: Config, target: Target): string {
    const jobOutputs = target.resolvedJobs.flatMap((job) => {
        if (job.addOutputsToTargetSources) {
            return job.outputs;
        } else {
            return [];
        }
    });

    let str = '';
    const targetSources = [...target.sources, ...jobOutputs];
    const targetSourcesStr = targetSources.join(' ');
    let subtype = '';
    const targetType = getTargetType(target);
    switch (targetType) {
        case 'plain-exe':
        case 'windowed-exe':
            if (targetType === 'windowed-exe') {
                if (config.platform === 'windows') {
                    subtype = ' WIN32';
                } else if ((config.platform === 'macos') || (config.platform === 'ios')) {
                    subtype = ' MACOSX_BUNDLE';
                }
            }
            str += `add_executable(${target.name}${subtype} ${targetSourcesStr})\n`;
            break;
        case 'lib':
            str += `add_library(${target.name} STATIC EXCLUDE_FROM_ALL ${targetSourcesStr})\n`;
            break;
        case 'dll':
            str += `add_library(${target.name} SHARED ${targetSourcesStr})\n`;
            break;
        case 'interface':
            str += `add_library(${target.name} INTERFACE ${targetSourcesStr})\n`;
            break;
    }
    str += `source_group(TREE ${target.dir} FILES ${target.sources.join(' ')})\n`;
    if (jobOutputs.length > 0) {
        str += `source_group(gen FILES ${jobOutputs.join(' ')})\n`;
    }
    return str;
}

function genTargetDependencies(target: Target, jobPlan: JobPlan): string {
    let str = '';
    const scope = getTargetType(target) === 'interface' ? ' INTERFACE' : '';
    const libs = [...target.deps, ...target.libs];
    if (libs.length > 0) {
        str += `target_link_libraries(${target.name}${scope} ${libs.join(' ')})\n`;
    }
    // macOS frameworks need special formatting
    const fws = target.frameworks;
    if (fws.length > 0) {
        str += `target_link_libraries(${target.name}${scope} ${fws.map((fw) => `"-framework ${fw}"`).join(' ')})\n`;
    }
    const jobTargets = [...new Set((jobPlan.targetJobs.get(target.name) ?? []).map((planned) => jobsTargetName(planned.owner)))];
    if (jobTargets.length > 0) {
        str += `add_dependencies(${target.name} ${jobTargets.join(' ')})\n`;
    }
    return str;
}

function genTargetIncludeDirectories(target: Target): string {
    let str = '';
    target.includeDirectories.forEach((item) => {
        const sys = item.system ? ' SYSTEM' : '';
        const scope = asCmakeScope(item.scope);
        str += `target_include_directories(${target.name}${sys}${scope} ${compileExpr(item.language, item.buildMode, item.dir)})\n`;
    });
    return str;
}

function genTargetLinkDirectories(target: Target): string {
    let str = '';
    target.linkDirectories.forEach((item) => {
        const scope = asCmakeScope(item.scope);
        str += `target_link_directories(${target.name}${scope} ${compileExpr(item.language, item.buildMode, item.dir)})\n`;
    });
    return str;
}

function genTargetCompileDefinitions(target: Target): string {
    let str = '';
    const items = target.compileDefinitions;
    if (items.length > 0) {
        str += `target_compile_definitions(${target.name}`;
        str += items.map((item) => `${asCmakeScope(item.scope)} ${compileExpr(item.language, item.buildMode, `${item.name}=${item.val}`)}`)
            .join(
                ' ',
            );
        str += ')\n';
    }
    return str;
}

function genTargetCompileOptions(target: Target): string {
    let str = '';
    const items = target.compileOptions;
    if (items.length > 0) {
        str += `target_compile_options(${target.name}`;
        str += items.map((item) => `${asCmakeScope(item.scope)} ${compileExpr(item.language, item.buildMode, item.opt)}`).join(' ');
        str += ')\n';
    }
    return str;
}

function genTargetLinkOptions(target: Target): string {
    let str = '';
    const items = target.linkOptions;
    if (items.length > 0) {
        str += `target_link_options(${target.name}`;
        str += items.map((item) => `${asCmakeScope(item.scope)} ${linkExpr(item.language, item.buildMode, item.opt)}`).join(' ');
        str += ')\n';
    }
    return str;
}

function genTargetProperties(target: Target): string {
    let str = '';
    const items = Object.entries(target.props);
    if (target.ideFolder !== undefined) {
        str += `set_target_properties(${target.name} PROPERTIES FOLDER ${target.ideFolder})\n`;
    }
    if (items.length > 0) {
        str += `set_target_properties(${target.name} PROPERTIES `;
        str += items.map(([key, val]) => `${key} ${val}`).join(' ');
        str += ')\n';
    }
    return str;
}

// each job gets its own build rule, the rules of a target's jobs are driven by a
// '[target]-jobs' custom target which the target itself depends on
function genJobs(project: Project, jobPlan: JobPlan): string {
    let str = '';
    for (const planned of jobPlan.jobs) {
        str += genJobRule(planned);
    }
    for (const target of project.targets()) {
        const owned = (jobPlan.targetJobs.get(target.name) ?? []).filter((planned) => planned.owner === target);
        if (owned.length === 0) {
            continue;
        }
        const name = jobsTargetName(target);
        const outputs = owned.flatMap((planned) => planned.job.outputs);
        str += `add_custom_target(${name} DEPENDS ${outputs.map(quote).join(' ')})\n`;
        str += `set_target_properties(${name} PROPERTIES FOLDER jobs)\n`;
        // jobs which use outputs of other targets' jobs must run after those
        const producerTargets = new Set(owned.flatMap((planned) =>
            planned.job.inputs.flatMap((input) => {
                const producer = jobPlan.producers.get(input);
                return ((producer !== undefined) && (producer.owner !== target)) ? [jobsTargetName(producer.owner)] : [];
            })
        ));
        if (producerTargets.size > 0) {
            str += `add_dependencies(${name} ${[...producerTargets].join(' ')})\n`;
        }
    }
    return str;
}

function genJobRule(planned: PlannedJob): string {
    const { job, owner, jobFile } = planned;
    const depends = [...job.inputs];
    const commands: string[] = [];
    // make sure that output directories exist
    const outputDirs = [...new Set(job.outputs.map((output) => path.dirname(output)))];
    commands.push(`\${CMAKE_COMMAND} -E make_directory ${outputDirs.map(quote).join(' ')}`);
    if (jobFile === undefined) {
        commands.push(...job.commands!.map(genJobCommand));
        // NOTE: depending on targets also adds a file-level dependency on the target's executable
        depends.push(...commandTargets(job));
    } else {
        commands.push(`\${DENO} run --allow-all --no-config ${quote(jobFibsRoot())} runjob ${quote(jobFile)}`);
        depends.push(jobFile, job.builder.modulePath);
    }
    let str = `add_custom_command(OUTPUT ${job.outputs.map(quote).join(' ')}\n`;
    if (depends.length > 0) {
        str += `    DEPENDS ${depends.map(quote).join(' ')}\n`;
    }
    for (const cmd of commands) {
        str += `    COMMAND ${cmd}\n`;
    }
    // NOTE: relative paths in job commands are relative to the target directory (same as job inputs and outputs)
    str += `    WORKING_DIRECTORY ${quote(owner.dir)}\n`;
    str += `    COMMENT ${quote(`Running job ${job.name} (${owner.name})`)}\n`;
    str += '    VERBATIM)\n';
    return str;
}

function genJobCommand(cmd: JobCommand): string {
    return cmd.map((arg, index) => {
        if (typeof arg === 'object') {
            // the first command item must be the target name for cmake to resolve the executable
            return (index === 0) ? arg.target : `$<TARGET_FILE:${arg.target}>`;
        } else if ((index === 0) && (arg === 'cmake')) {
            return '${CMAKE_COMMAND}';
        } else {
            return quote(arg);
        }
    }).join(' ');
}

function jobsTargetName(target: Target): string {
    return `${target.name}-jobs`;
}

// quote and escape a string as cmake argument
function quote(str: string): string {
    return `"${str.replace(/[\\"$]/g, '\\$&')}"`;
}

// the fibs root module for running script jobs at build time, this is pinned
// to the same fibs version (or local fibs directory) which generated the build files
function jobFibsRoot(): string {
    const jsrMatch = import.meta.url.match(/^https:\/\/jsr\.io\/@floooh\/fibs\/([^/]+)\//);
    if (jsrMatch) {
        return `jsr:@floooh/fibs@${jsrMatch[1]}`;
    } else if (import.meta.url.startsWith('file:')) {
        return path.fromFileUrl(new URL('../../index.ts', import.meta.url)).replaceAll('\\', '/');
    } else {
        return 'jsr:@floooh/fibs';
    }
}
